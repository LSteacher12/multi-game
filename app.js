function normalizeAnswer(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

function setupJeopardy() {
  const board = document.querySelector('#jeopardy-board');
  if (!board) return;

  const scoreElement = document.querySelector('#board-score');
  const progressElement = document.querySelector('#board-progress');
  const dialog = document.querySelector('#clue-dialog');
  const answerForm = document.querySelector('#clue-answer-form');
  const answerInput = document.querySelector('#clue-answer');
  const feedback = document.querySelector('#clue-feedback');
  const submitButton = document.querySelector('#clue-submit');
  const passButton = document.querySelector('#clue-pass');
  const continueButton = document.querySelector('#clue-continue');
  let score = 0;
  let completed = 0;
  let activeClue;

  const updateScore = (amount) => {
    score += amount;
    scoreElement.textContent = score.toLocaleString();
  };

  const finishClue = (message, isWrong = false) => {
    const { button, clue } = activeClue;
    button.disabled = true;
    button.textContent = '—';
    button.setAttribute('aria-label', `${activeClue.category}, ${clue.value} points, completed`);
    completed += 1;
    progressElement.textContent = `${20 - completed} ${20 - completed === 1 ? 'clue' : 'clues'} waiting`;
    feedback.textContent = message;
    feedback.classList.toggle('is-wrong', isWrong);
    answerInput.disabled = true;
    submitButton.hidden = true;
    passButton.hidden = true;
    continueButton.hidden = false;
  };

  const renderBoard = () => {
    board.replaceChildren();
    boardCategories.forEach((category) => {
      const column = document.createElement('section');
      column.className = 'category-column';
      const heading = document.createElement('h3');
      heading.className = 'category-title';
      heading.textContent = category.title;
      column.append(heading);

      category.clues.forEach((clue) => {
        const button = document.createElement('button');
        button.className = 'clue-tile';
        button.type = 'button';
        button.textContent = clue.value;
        button.setAttribute('aria-label', `${category.title}, ${clue.value} points`);
        button.addEventListener('click', () => {
          activeClue = { category: category.title, clue, button };
          document.querySelector('#clue-category').textContent = category.title;
          document.querySelector('#clue-value').textContent = `${clue.value} points`;
          document.querySelector('#clue-text').textContent = clue.prompt;
          feedback.textContent = '';
          feedback.classList.remove('is-wrong');
          answerInput.value = '';
          answerInput.disabled = false;
          submitButton.hidden = false;
          passButton.hidden = false;
          continueButton.hidden = true;
          dialog.showModal();
          answerInput.focus();
        });
        column.append(button);
      });
      board.append(column);
    });
  };

  answerForm.addEventListener('submit', (event) => {
    event.preventDefault();
    const guess = normalizeAnswer(answerInput.value);
    const correct = activeClue.clue.answers.some((answer) => normalizeAnswer(answer) === guess);
    const accepted = activeClue.clue.answers[0];
    if (correct) {
      updateScore(activeClue.clue.value);
      finishClue(`That's right! +${activeClue.clue.value} points.`);
    } else {
      updateScore(-activeClue.clue.value);
      finishClue(`Not quite. The answer was ${accepted}. −${activeClue.clue.value} points.`, true);
    }
  });

  passButton.addEventListener('click', () => {
    finishClue(`The answer was ${activeClue.clue.answers[0]}.`, true);
  });

  continueButton.addEventListener('click', () => dialog.close());

  document.querySelector('#board-reset').addEventListener('click', () => {
    score = 0;
    completed = 0;
    scoreElement.textContent = '0';
    progressElement.textContent = '20 clues waiting';
    if (dialog.open) dialog.close();
    renderBoard();
  });

  renderBoard();
}

