function setupTrivia() {
  const panel = document.querySelector('#quiz-panel');
  if (!panel) return;

  const questionElement = document.querySelector('#trivia-heading');
  const optionsElement = document.querySelector('#answer-options');
  const feedbackElement = document.querySelector('#quiz-feedback');
  const nextButton = document.querySelector('#quiz-next');
  const scoreElement = document.querySelector('#trivia-score');
  const countElement = document.querySelector('#quiz-count');
  const progressBar = document.querySelector('#quiz-progress-bar');
  const content = document.querySelector('#quiz-content');
  const results = document.querySelector('#quiz-results');
  let questionIndex = 0;
  let score = 0;
  let answered = false;

  const renderQuestion = () => {
    const current = triviaQuestions[questionIndex];
    answered = false;
    countElement.textContent = `QUESTION ${questionIndex + 1} / ${triviaQuestions.length}`;
    progressBar.style.width = `${(questionIndex / triviaQuestions.length) * 100}%`;
    questionElement.textContent = current.question;
    feedbackElement.textContent = '';
    feedbackElement.classList.remove('is-wrong');
    nextButton.hidden = true;
    optionsElement.replaceChildren();

    current.options.forEach((option, index) => {
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'answer-option';
      button.textContent = option;
      button.addEventListener('click', () => chooseAnswer(button, option, current.answer));
      optionsElement.append(button);
    });
  };

  const chooseAnswer = (selectedButton, selection, correctAnswer) => {
    if (answered) return;
    answered = true;
    const correct = selection === correctAnswer;
    optionsElement.querySelectorAll('button').forEach((button) => {
      button.disabled = true;
      if (button.textContent === correctAnswer) button.classList.add('is-correct');
    });

    if (correct) {
      score += 100;
      scoreElement.textContent = score.toLocaleString();
      feedbackElement.textContent = 'Exactly right. +100 points.';
    } else {
      selectedButton.classList.add('is-wrong');
      feedbackElement.textContent = `Not this time. The answer was ${correctAnswer}.`;
      feedbackElement.classList.add('is-wrong');
    }

    nextButton.textContent = questionIndex === triviaQuestions.length - 1 ? 'See your score' : 'Next question →';
    nextButton.hidden = false;
    progressBar.style.width = `${((questionIndex + 1) / triviaQuestions.length) * 100}%`;
  };

  const finishQuiz = () => {
    content.hidden = true;
    results.hidden = false;
    progressBar.style.width = '100%';
    countElement.textContent = 'ROUND COMPLETE';
    document.querySelector('#final-score').textContent = score.toLocaleString();
    const correctCount = score / 100;
    document.querySelector('#result-message').textContent = correctCount === triviaQuestions.length
      ? 'A perfect round. You really know your stuff.'
      : `${correctCount} of ${triviaQuestions.length} answers were right. Ready for another round?`;
  };

  nextButton.addEventListener('click', () => {
    questionIndex += 1;
    if (questionIndex === triviaQuestions.length) finishQuiz();
    else renderQuestion();
  });

  document.querySelector('#quiz-restart').addEventListener('click', () => {
    questionIndex = 0;
    score = 0;
    scoreElement.textContent = '0';
    content.hidden = false;
    results.hidden = true;
    renderQuestion();
  });

  renderQuestion();
}

if (page === 'jeopardy') setupJeopardy();
